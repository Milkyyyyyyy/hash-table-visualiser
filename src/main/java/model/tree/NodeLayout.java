package model.tree;

/**
 * Хранит информацию о расположении и анимации узла на экране.
 *
 * Отвечает за отслеживание:
 * - Текущей позиции узла (обновляется каждый кадр для анимации)
 * - Целевой позиции узла (вычисляется при обновлении дерева)
 * - Состояния подсветки узла (активен/неактивен)
 *
 * Используется рендерером для плавной интерполяции (lerp) позиции при движении узлов.
 */
public class NodeLayout {

    /** Текущая X-координата узла (обновляется при анимации). */
    public float x;

    /** Текущая Y-координата узла (обновляется при анимации). */
    public float y;

    /** Целевая X-координата узла, к которой он должен двигаться. */
    public float targetX;

    /** Целевая Y-координата узла, к которой он должен двигаться. */
    public float targetY;

    /** Флаг, указывающий на подсветку узла (используется рендерером для окраски). */
    public boolean isActive = false;

    /**
     * Создаёт описание расположения узла с заданной начальной позицией.
     * Целевые координаты инициализируются теми же значениями.
     *
     * @param x начальная X-координата
     * @param y начальная Y-координата
     */
    public NodeLayout(float x, float y) {
        this.x = x;
        this.y = y;
        this.targetX = x;
        this.targetY = y;
    }
}
